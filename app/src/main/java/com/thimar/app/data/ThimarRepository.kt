    fun sendAiMessage(question: String) {
        val userMsg = ChatMessage(System.currentTimeMillis().toString(), "أنت", question, true, "الآن")
        val aiReplyText = when {
            question.contains("تجويد") || question.contains("أحكام") ->
                "أحكام التجويد الأساسية تبدأ بالنون الساكنة والتنوين: الإظهار، الإدغام، الإقلاب، والإخفاء، كما نظّمها الجمزوري في تحفة الأطفال."
            question.contains("حفظ") || question.contains("مراجعة") ->
                "أفضل طريقة لتثبيت الحفظ هي ربط الآيات بالمعاني، والتكرار ٧ مرات غيباً، ومراجعة المحفوظ في صلاة قيام الليل والصلوات الخمس."
            question.contains("النور") ->
                "سورة النور مدنية، عدد آياتها ٦٤، ومن مقاصدها حفظ المجتمع وحماية الأعراض ونور الهداية والإيمان."
            else ->
                "بارك الله فيك! أسأل الله أن يجعلك من أهل القرآن الذين هم أهل الله وخاصته. يمكنك استعراض المتن أو المصحف لمتابعة وردك."
        }
        val aiMsg = ChatMessage((System.currentTimeMillis() + 1).toString(), "ثمار AI", aiReplyText, false, "الآن")
        _chatMessages.value = _chatMessages.value + userMsg + aiMsg
    }

