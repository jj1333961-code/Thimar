  var locale = localStorage.getItem('lang') === 'en' ? 'en' : 'ar';
  var originals = new WeakMap();
  var attributeNames = ['placeholder', 'title', 'aria-label', 'aria-description', 'alt', 'value'];
  var protectedTags = ['SCRIPT', 'STYLE', 'CODE', 'PRE', 'NOSCRIPT'];
  var arabicDigits = ['٠','١','٢','٣','٤','٥','٦','٧','٨','٩'];

  function convertArabicDigits(str) {
    if (!str || typeof str !== 'string') return str;
    return str.replace(/[٠-٩]/g, function (d) {
      var idx = arabicDigits.indexOf(d);
      return idx !== -1 ? String(idx) : d;
    }).replace(/٪/g, '%').replace(/،/g, ',').replace(/؛/g, ';').replace(/؟/g, '?');
  }

  function isProtected(node) {
    if (!node) return true;
    var el = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    if (!el) return false;
    if (protectedTags.indexOf(el.tagName) !== -1) return true;
    return false;
  }

  function dictionaryFor(target) {
    if (target === 'en') return dictionaries.en;
    if (!dictionaries._ar) {
      dictionaries._ar = Object.keys(dictionaries.en).reduce(function (result, key) {
        if (!result[dictionaries.en[key]]) result[dictionaries.en[key]] = key;
        return result;
      }, {});
    }
    return dictionaries._ar;
  }

  function escapeRegex(s) {
    return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }

  var sortedEnKeys = null;
  function getSortedKeys(target) {
    if (target === 'en') {
      if (!sortedEnKeys) {
        sortedEnKeys = Object.keys(dictionaries.en).sort(function (a, b) { return b.length - a.length; });
      }
      return sortedEnKeys;
    }
    var dict = dictionaryFor(target);
    return Object.keys(dict).sort(function (a, b) { return b.length - a.length; });
  }

  function translate(value, target) {
    if (!value || typeof value !== 'string') return value;
    var targetLocale = target || locale;
    var dict = dictionaryFor(targetLocale);

    var text = value;
    if (targetLocale === 'en') {
      text = convertArabicDigits(text);
    }

    var trimmed = text.trim();
    if (!trimmed) return text;

    if (dict[trimmed]) {
      return text.replace(trimmed, dict[trimmed]);
    }

    // Try stripping leading/trailing asterisks, colons, brackets
    var punctMatch = trimmed.match(/^([*:•\-\s]*)(.*?)([*:•\-\s]*)$/);
    if (punctMatch && punctMatch[2] && punctMatch[2] !== trimmed) {
      var core = punctMatch[2];
      if (dict[core]) {
        return text.replace(trimmed, punctMatch[1] + dict[core] + punctMatch[3]);
      }
    }

    var result = text;
    var keys = getSortedKeys(targetLocale);
    for (var i = 0; i < keys.length; i++) {
      var key = keys[i];
      if (result.indexOf(key) === -1) continue;
      var repl = dict[key];
      if (key.indexOf(' ') !== -1 || key.length > 4) {
        result = result.split(key).join(repl);
      } else {
        try {
          var re = new RegExp('(^|[^a-zA-Z0-9_؀-ۿ])' + escapeRegex(key) + '(?=[^a-zA-Z0-9_؀-ۿ]|$)', 'g');
          result = result.replace(re, '$1' + repl);
        } catch (e) {
          result = result.split(key).join(repl);
        }
      }
    }
    return result;
  }

  function applyText(root) {
    if (!root) return;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    var node;
    while ((node = walker.nextNode())) {
      if (!node.nodeValue || !node.nodeValue.trim() || isProtected(node)) continue;
      if (!originals.has(node)) originals.set(node, node.nodeValue);
      var source = originals.get(node);
      if (locale === 'ar') {
        if (/[\u0600-\u06FF]/.test(source)) {
          node.nodeValue = source;
        } else {
          node.nodeValue = translate(source, 'ar');
        }
      } else {
        node.nodeValue = translate(source, 'en');
      }
    }
  }

  function applyAttributes(root) {
    var elements = [];
    if (root && root.nodeType === Node.ELEMENT_NODE) elements.push(root);
    if (root && root.querySelectorAll) {
      elements = elements.concat(Array.prototype.slice.call(root.querySelectorAll('input,textarea,button,select,option,[title],[aria-label],[aria-description],[alt]')));
    }
    elements.forEach(function (element) {
      if (isProtected(element)) return;

      if (element.tagName === 'OPTION') {
        if (!element.hasAttribute('data-i18n-orig-text')) {
          element.setAttribute('data-i18n-orig-text', element.textContent || '');
        }
        var origOptText = element.getAttribute('data-i18n-orig-text') || '';
        if (locale === 'ar') {
          element.textContent = /[\u0600-\u06FF]/.test(origOptText) ? origOptText : translate(origOptText, 'ar');
        } else {
          element.textContent = translate(origOptText, 'en');
        }
      }

      attributeNames.forEach(function (attribute) {
        if (!element.hasAttribute(attribute)) return;
        if (attribute === 'value' && !['button', 'submit', 'reset'].includes(String(element.type || '').toLowerCase())) return;
        var key = 'data-i18n-original-' + attribute;
        if (!element.hasAttribute(key)) element.setAttribute(key, element.getAttribute(attribute) || '');
        var source = element.getAttribute(key) || '';
        if (locale === 'ar') {
          if (/[\u0600-\u06FF]/.test(source)) {
            element.setAttribute(attribute, source);
          } else {
            element.setAttribute(attribute, translate(source, 'ar'));
          }
        } else {
          element.setAttribute(attribute, translate(source, 'en'));
        }
      });
    });
  }

  function apply(root) {
    if (!root) return;
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'en' ? 'ltr' : 'rtl';
    document.title = (locale === 'en') ? 'Thimar - Quran Memorization Platform' : 'ثمار - منصة حفظ القرآن الكريم';

    applyText(root);
    applyAttributes(root);

    var button = document.getElementById('langToggleBtn');
    if (button) {
      button.textContent = locale === 'en' ? 'ع' : 'EN';
      button.setAttribute('aria-label', locale === 'en' ? 'التبديل إلى العربية' : 'Switch to English');
    }
    document.querySelectorAll('.country-search').forEach(function (search) {
      search.placeholder = locale === 'en' ? 'Search countries' : 'بحث عن الدولة';
      search.setAttribute('aria-label', locale === 'en' ? 'Search countries' : 'بحث عن الدولة');
    });
  }

  // Intercept window.alert, window.confirm, window.prompt
  try {
    var rawAlert = window.alert;
    window.alert = function (msg) {
      var out = msg;
      if (locale === 'en' && typeof msg === 'string') {
        out = translate(msg, 'en');
      }
      return rawAlert.call(window, out);
    };
    var rawConfirm = window.confirm;
    window.confirm = function (msg) {
      var out = msg;
      if (locale === 'en' && typeof msg === 'string') {
        out = translate(msg, 'en');
      }
      return rawConfirm.call(window, out);
    };
    var rawPrompt = window.prompt;
    window.prompt = function (msg, def) {
      var out = msg;
      if (locale === 'en' && typeof msg === 'string') {
        out = translate(msg, 'en');
      }
      return rawPrompt.call(window, out, def);
    };
  } catch (e) {}

  var isChangingLang = false;
  function setLocale(next) {
    if (isChangingLang) return;
    isChangingLang = true;
    try {
      locale = next === 'en' ? 'en' : 'ar';
      localStorage.setItem('lang', locale);
      apply(document.body);
    } finally {
      isChangingLang = false;
    }
  }

  window.ThimarI18n = {
    apply: apply,
    setLocale: setLocale,
    t: function (value) { return translate(value, locale); },
    getLocale: function () { return locale; },
    convertDigits: convertArabicDigits
  };

  window.addEventListener('languagechange', function () {
    if (isChangingLang) return;
    isChangingLang = true;
    try {
      locale = localStorage.getItem('lang') === 'en' ? 'en' : 'ar';
      apply(document.body);
    } finally {
      isChangingLang = false;
    }
  });

  var observerFrame = 0;
  var isApplying = false;
  var pendingRoots = [];

  function scheduleApply(root) {
    if (!root || isApplying) return;
    if (pendingRoots.indexOf(root) === -1) pendingRoots.push(root);
    if (observerFrame) return;
    var flush = function () {
      observerFrame = 0;
      if (isApplying) return;
      isApplying = true;
      try {
        var roots = pendingRoots.splice(0, pendingRoots.length);
        roots.forEach(function (r) {
          try { apply(r); } catch (e) {}
        });
      } finally {
        isApplying = false;
      }
    };
    observerFrame = typeof requestAnimationFrame === 'function' ? requestAnimationFrame(flush) : setTimeout(flush, 0);
  }

  function init() {
    isApplying = true;
    try {
      apply(document.body);
    } finally {
      isApplying = false;
    }
    var observer = new MutationObserver(function (records) {
      if (isApplying) return;
      records.forEach(function (record) {
        if (record.type === 'characterData') {
          scheduleApply(record.target.parentElement || document.body);
        } else if (record.type === 'childList') {
          Array.prototype.forEach.call(record.addedNodes, function (added) {
            if (added.nodeType === Node.ELEMENT_NODE || added.nodeType === Node.TEXT_NODE) {
              scheduleApply(added.nodeType === Node.TEXT_NODE ? added.parentElement : added);
            }
          });
        }
      });
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
